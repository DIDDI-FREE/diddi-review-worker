from typing import Protocol


class GooglePlayDriver(Protocol):
    """Boundary for a real mobile E2E tool such as Appium or Maestro."""

    async def open_app(self) -> None: ...
    async def sign_in_single_google_account(self) -> None: ...
    async def execute_user_journey(self, scenario: str) -> dict[str, str]: ...
    async def assert_final_state(self, expected: str) -> None: ...

